#!/bin/sh
set -e

# Схема БД: создаём базу и таблицы, если их нет.
alembic upgrade head

# Проверяем, что схема совпадает с моделями. create_all не меняет уже
# существующие таблицы, поэтому после правки модели приложение упало бы
# позже и не там, где ошибку ищут. Лучше не подняться вовсе и сказать почему.
python -m scripts.check_schema

# Администратор из .env + тестовые данные (идемпотентно, дубли не создаются).
python -m scripts.seed_all

exec "$@"
